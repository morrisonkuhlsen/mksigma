/// Correct significant digits of `x` against `certified` (absolute digits when it is 0), at
/// most 15.
fn lre(x: f64, certified: f64) -> f64 {
    // An F with no residual at all is infinite; one past 1/ε, whose residual is only rounding,
    // is as good.
    if certified.is_infinite() {
        return if x == certified || x.abs() > 1.0 / f64::EPSILON { 15.0 } else { 0.0 };
    }
    let error = if certified == 0.0 { (x - certified).abs() } else { ((x - certified) / certified).abs() };
    if error == 0.0 { 15.0 } else { (-error.log10()).min(15.0) }
}

fn assert_digits(what: &str, x: f64, certified: f64, digits: f64) {
    let got = lre(x, certified);
    eprintln!("LRE {got:5.1}  {what}");
    assert!(got >= digits, "{what}: {x} against the certified {certified}: {got:.1} digits, fewer than {digits}");
}

/// A dataset of numeric columns.
fn dataset(columns: &[(&str, &[f64])]) -> Dataset {
    let mut ds = Dataset::new();
    for (name, _) in columns {
        ds.add_variable(Variable::numeric(*name)).unwrap();
    }
    let n = columns.first().map_or(0, |(_, c)| c.len());
    for i in 0..n {
        ds.push_case(columns.iter().map(|(_, c)| Value::Num(c[i])).collect()).unwrap();
    }
    ds
}

fn value(cell: &Cell) -> f64 {
    match cell {
        Cell::Num { value, .. } | Cell::Sig(value) => *value,
        Cell::Int(k) => *k as f64,
        // A figure that isn't finite (an F with no residual) is left empty.
        Cell::Empty => f64::INFINITY,
        other => panic!("not a number: {other:?}"),
    }
}

fn tables(items: &[Item]) -> Vec<&Table> {
    items.iter().filter_map(|i| if let Item::Table(t) = i { Some(t) } else { None }).collect()
}

/// Its certified mean and standard deviation (n − 1), through DESCRIPTIVES.
fn univariate(name: &str, values: &[f64], mean: f64, sd: f64, digits: f64) {
    let ds = dataset(&[("y", values)]);
    let table = mksigma_stats::descriptives(&ds, &["y".into()]).unwrap();
    let cells = &table.rows[0].1;
    assert_eq!(value(&cells[0]), values.len() as f64, "{name}: N");
    assert_digits(&format!("{name}: mean"), value(&cells[3]), mean, digits);
    assert_digits(&format!("{name}: standard deviation"), value(&cells[4]), sd, digits);
}

/// The certified analysis of variance (between: df, SS, MS, F; within: df, SS, MS, in NIST's
/// order), through ONEWAY.
fn anova(name: &str, groups: &[f64], values: &[f64], between: [f64; 4], within: [f64; 3], digits: f64) {
    let ds = dataset(&[("g", groups), ("y", values)]);
    let options = OnewayOptions { dependents: vec!["y".into()], factor: "g".into(), ..OnewayOptions::default() };
    let items = mksigma_stats::oneway(&ds, &options).unwrap();
    let table = tables(&items).into_iter().find(|t| t.title == "ANOVA").unwrap();
    let (b, w) = (&table.rows[0].1, &table.rows[1].1);
    // The table's columns: SS, df, MS, F.
    for (k, at, what) in [(1, 1, "between SS"), (2, 0, "between df"), (3, 2, "between MS"), (4, 3, "F")] {
        assert_digits(&format!("{name}: {what}"), value(&b[k]), between[at], digits);
    }
    for (k, at, what) in [(1, 1, "within SS"), (2, 0, "within df"), (3, 2, "within MS")] {
        assert_digits(&format!("{name}: {what}"), value(&w[k]), within[at], digits);
    }
}

/// A regression's certified coefficients with their standard errors, residual standard
/// deviation, R², and analysis of variance (regression: SS, MS, F; residual: SS, MS).
struct Certified<'a> {
    b: &'a [(f64, f64)],
    sd: f64,
    r2: f64,
    regression: [f64; 3],
    residual: [f64; 2],
}

/// `y` on the predictors `xs`, through REGRESSION.
fn linear(name: &str, y: &[f64], xs: &[Vec<f64>], c: &Certified, origin: bool, digits: f64) {
    let names: Vec<String> = (1..=xs.len()).map(|k| format!("x{k}")).collect();
    let mut columns: Vec<(&str, &[f64])> = vec![("y", y)];
    columns.extend(names.iter().map(String::as_str).zip(xs.iter().map(Vec::as_slice)));
    let ds = dataset(&columns);
    // Every predictor enters, as NIST certifies the full model: the lowest tolerance there is.
    let options = RegressionOptions { dependent: "y".into(), predictors: names.clone(), ci: None, tolerance: f64::MIN_POSITIVE, origin };
    let items = mksigma_stats::regression(&ds, &options).unwrap();
    let t = tables(&items);
    if t.is_empty() {
        eprintln!("LRE   0.0  {name}: refused, {items:?}");
        assert!(digits == 0.0, "{name}: no model, {items:?}");
        return;
    }
    let (summary, anova, coefficients) = (&t[0].rows[0].1, &t[1].rows, &t[2].rows);
    for (k, (b, se)) in c.b.iter().enumerate() {
        let cells = &coefficients[k].1;
        // NIST counts from B0, the constant; through the origin the first is B1.
        let number = k + usize::from(origin);
        assert_digits(&format!("{name}: B{number}"), value(&cells[1]), *b, digits);
        assert_digits(&format!("{name}: SE of B{number}"), value(&cells[2]), *se, digits);
    }
    assert_digits(&format!("{name}: R²"), value(&summary[1]), c.r2, digits);
    assert_digits(&format!("{name}: residual SD"), value(&summary[3]), c.sd, digits);
    let (reg, res) = (&anova[0].1, &anova[1].1);
    for (k, at, what) in [(1, 0, "regression SS"), (3, 1, "regression MS"), (4, 2, "F")] {
        assert_digits(&format!("{name}: {what}"), value(&reg[k]), c.regression[at], digits);
    }
    for (k, at, what) in [(1, 0, "residual SS"), (3, 1, "residual MS")] {
        assert_digits(&format!("{name}: {what}"), value(&res[k]), c.residual[at], digits);
    }
}

/// `x`, `x²`, … `x^degree`.
fn powers(x: &[f64], degree: usize) -> Vec<Vec<f64>> {
    (1..=degree).map(|k| x.iter().map(|v| v.powi(k as i32)).collect()).collect()
}

/// PiDigits: the first 5000 decimal digits of π (3, 1, 4, 1, 5, …).
fn pi_digits() -> Vec<f64> {
    PI.chars().filter_map(|c| c.to_digit(10)).map(f64::from).collect()
}

/// `1 + 2k` values: the centre, then `k` pairs a tenth below and above it, written as decimals
/// (`1000000.2`) and read as the files' text is.
fn around(whole: &str, tenth: u32, k: usize) -> Vec<f64> {
    let at = |t: u32| format!("{whole}.{t}").parse::<f64>().unwrap();
    let mut v = vec![at(tenth)];
    for _ in 0..k {
        v.push(at(tenth - 1));
        v.push(at(tenth + 1));
    }
    v
}

/// SmLs01–09: nine groups of `1 + 2k` values around centres x.4, x.3, x.5, x.3, … .
fn smls(whole: &str, k: usize) -> (Vec<f64>, Vec<f64>) {
    let (mut g, mut y) = (Vec::new(), Vec::new());
    for (group, tenth) in [4, 3, 5, 3, 5, 3, 5, 3, 5].into_iter().enumerate() {
        for v in around(whole, tenth, k) {
            g.push(group as f64 + 1.0);
            y.push(v);
        }
    }
    (g, y)
}

