//! The NIST Statistical Reference Datasets (StRD; https://www.itl.nist.gov/div898/strd/,
//! public domain, from the U.S. National Institute of Standards and Technology): datasets with
//! certified results computed in multiple precision, the usual audit of a statistics package's
//! accuracy. The data are built here in code (the long constructed ones by their rule) and the certified values re-typed as constants. Each figure is held to a
//! number of correct significant digits, its LRE (log relative error, −log₁₀ |x − c| / |c|).
//!
//! Univariate summary statistics go through DESCRIPTIVES, the analyses of variance through
//! ONEWAY, the linear regressions through REGRESSION (NoInt1 and NoInt2 with /ORIGIN). Not
//! covered yet: the autocorrelation (not a statistic MK Sigma reports) and the nonlinear
//! regressions.
